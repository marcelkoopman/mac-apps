//! "Keep clipboard history" (Klembordgeschiedenis bijhouden): whether CopyCraft watches the
//! clipboard on its own, or works paste-first and takes only what the user pastes into the card
//! (⌘V) or drops on it. Pure logic; the setting is stored in `settings.rs`, and the pasteboard
//! reader (`macos_pasteboard`) and the poller (`menubar/state.rs`) ask [`read_allowed`].
//!
//! Off (the default on a new install): no polling, not even of the change count, and no read
//! when the card opens. ⌘V reads the pasteboard once, because the user asked for it. Pause,
//! Ignore Next Copy and the ignored apps only do something while history is on
//! ([`capture_controls_active`]).

use zeroize::Zeroizing;

/// Why CopyCraft would read the general pasteboard.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ReadTrigger {
    /// The background poll: the change count, then a new copy.
    Poll,
    /// The card opens or refreshes (with Default or Ask pasteboard privacy a copy is read then).
    CardOpen,
    /// ⌘V in the card: the user asks for what is on the clipboard.
    ExplicitPaste,
}

/// Whether a read for `trigger` may happen. An explicit paste always may; the poll and the
/// read when the card opens only while history is kept.
pub fn read_allowed(keep_history: bool, trigger: ReadTrigger) -> bool {
    match trigger {
        ReadTrigger::ExplicitPaste => true,
        ReadTrigger::Poll | ReadTrigger::CardOpen => keep_history,
    }
}

/// The setting when it was never stored: on for an existing install (the welcome window was
/// closed before, or any other setting is stored), so it keeps watching as before; off for a
/// new install. A stored value always wins.
pub fn keep_history_default(
    stored: Option<bool>,
    welcome_seen: bool,
    other_settings: bool,
) -> bool {
    stored.unwrap_or(welcome_seen || other_settings)
}

/// Pause, Ignore Next Copy and the ignored apps decide which copies are read while watching;
/// without watching there is nothing for them to hold back, so they are greyed out.
pub fn capture_controls_active(keep_history: bool) -> bool {
    keep_history
}

/// What ⌘V found on the clipboard, read once on the main thread while the key is handled.
#[derive(Debug, Clone)]
pub enum Pasted {
    /// Text. Zeroized when dropped.
    Text(Zeroizing<String>),
    /// An encoded picture (PNG, JPEG, TIFF, …). Zeroized when dropped.
    Image(Zeroizing<Vec<u8>>),
    /// Another app marked the copy private (Concealed, Transient, AutoGenerated): not read.
    Hidden,
    /// No text or picture (or the read was denied).
    Nothing,
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn no_pasteboard_reads_while_history_is_off() {
        assert!(!read_allowed(false, ReadTrigger::Poll));
        assert!(!read_allowed(false, ReadTrigger::CardOpen));
        // Only the user's own ⌘V reads it.
        assert!(read_allowed(false, ReadTrigger::ExplicitPaste));
    }

    #[test]
    fn history_on_reads_as_before() {
        assert!(read_allowed(true, ReadTrigger::Poll));
        assert!(read_allowed(true, ReadTrigger::CardOpen));
        assert!(read_allowed(true, ReadTrigger::ExplicitPaste));
    }

    #[test]
    fn a_new_install_starts_with_history_off() {
        assert!(!keep_history_default(None, false, false));
    }

    #[test]
    fn an_existing_install_keeps_watching() {
        // The welcome window was closed before…
        assert!(keep_history_default(None, true, false));
        // …or some other setting is stored.
        assert!(keep_history_default(None, false, true));
        assert!(keep_history_default(None, true, true));
    }

    #[test]
    fn a_stored_choice_wins() {
        for (seen, other) in [(false, false), (true, false), (false, true), (true, true)] {
            assert!(keep_history_default(Some(true), seen, other));
            assert!(!keep_history_default(Some(false), seen, other));
        }
    }

    #[test]
    fn capture_controls_follow_the_setting() {
        assert!(capture_controls_active(true));
        assert!(!capture_controls_active(false));
    }
}
