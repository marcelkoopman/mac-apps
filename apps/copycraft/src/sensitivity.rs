use std::sync::OnceLock;

use leakguard::{Kind, Match, Redactor};
use zeroize::Zeroizing;

use crate::format::FormatKind;

/// Clipboard categories shown on the card. Order is the meta-line order.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum Label {
    Credential,
    Pii,
    Financial,
}

impl Label {
    pub fn name(self) -> &'static str {
        match self {
            Self::Credential => crate::locale::t("label_credential"),
            Self::Pii => crate::locale::t("label_pii"),
            Self::Financial => crate::locale::t("label_financial"),
        }
    }

    const ALL: [Self; 3] = [Self::Credential, Self::Pii, Self::Financial];
}

/// Copies shorter than this are checked while the card is built. Longer ones go to the
/// background checker, and the card says [`checking`] until their labels arrive.
pub const SYNC_LIMIT: usize = 32 * 1024;
/// Meta-line status while the labels are not known yet. The card cannot be revealed meanwhile.
pub fn checking() -> &'static str {
    crate::locale::t("checking")
}

/// The labels found in a copy.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Found {
    pub labels: Vec<Label>,
}

/// What the card knows about a copy's labels.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Labeling {
    Known(Found),
    /// The background checker is on it; [`on_checked`]'s hook runs when it is done.
    Checking,
}

/// Whether a copy may go into history, from its labels.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Admission {
    Keep,
    /// It holds a credential (a token, key or URL password): it stays out of history. The card
    /// still shows it while it is on the clipboard.
    Refuse,
    /// A long copy whose labels are still being checked: decided once they are in.
    Wait,
}

/// May a copy with `labeling` go into history? Not when it holds a credential. PII and financial
/// data are kept (and masked by the privacy filter). Copies another app marks private
/// (Concealed, Transient, AutoGenerated) never get here: they are not read at all
/// ([`crate::clipboard::ClipboardView::Hidden`] has no text). Pure.
pub fn admission(labeling: &Labeling) -> Admission {
    match labeling {
        Labeling::Known(found) if found.labels.contains(&Label::Credential) => Admission::Refuse,
        Labeling::Known(_) => Admission::Keep,
        Labeling::Checking => Admission::Wait,
    }
}

/// When a drop, a ⌘V paste or a chosen file goes into history ([`record_when`]).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Record {
    Now,
    /// A long text whose labels are still being checked: decided again with the labels, once
    /// the background checker has them ([`on_checked`]). Not in history meanwhile.
    AfterCheck,
    /// It holds a credential: shown on the card, never in history.
    Never,
}

/// The [`Record`] for a copy's [`Admission`]. Only [`Admission::Keep`] goes in now; a long text
/// still being checked ([`Admission::Wait`]) waits for its labels, like a long copy from
/// another app does. Pure.
pub fn record_when(admission: Admission) -> Record {
    match admission {
        Admission::Keep => Record::Now,
        Admission::Wait => Record::AfterCheck,
        Admission::Refuse => Record::Never,
    }
}

/// May a picture go into history, now that its text recognition is done? `recognised` is the
/// text recognition found in it: `None` when it found no text, failed, timed out or there is no
/// text recogniser (then the picture is kept, as before). A picture whose recognised text holds
/// a token, key or URL password stays out ([`Admission::Refuse`]); the card still shows it.
/// Never [`Admission::Wait`]: a long recognised text is checked here and now (not by the
/// background checker, and its labels are not remembered). Pure.
pub fn picture_admission(recognised: Option<&str>) -> Admission {
    match recognised {
        None => Admission::Keep,
        Some(text) => admission(&Labeling::Known(Found {
            labels: scan_labels(text),
        })),
    }
}

/// A picture whose recognised text has any label (credential, PII, financial) goes on the
/// clipboard concealed, as such a text does (`App::write_own`). No text: plain.
pub fn picture_concealed(recognised: Option<&str>) -> bool {
    recognised.is_some_and(|text| !scan_labels(text).is_empty())
}

/// How an Image ▾ step's copy goes on the clipboard and into history.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct PictureVerdict {
    /// Marked Concealed (and cleared after a minute with that setting on).
    pub concealed: bool,
    /// Kept in history.
    pub admitted: bool,
}

/// The [`PictureVerdict`] for a picture whose recognised text is `recognised`
/// ([`picture_concealed`], [`picture_admission`]). An Image ▾ step's copy is made at once on
/// the text of the picture it was taken on (a step does not add text), and checked again when
/// its own recognition is in ([`picture_recheck`]). Pure.
pub fn picture_verdict(recognised: Option<&str>) -> PictureVerdict {
    PictureVerdict {
        concealed: picture_concealed(recognised),
        admitted: picture_admission(recognised) == Admission::Keep,
    }
}

/// How CopyCraft's own copy of a text with labels `found` goes on the clipboard and into
/// history (a Text ▾ step's result, an AI result): concealed with any label, kept out of
/// history with a credential. Its labels are always known here, never still being checked: a
/// long step result is checked on the step's own thread, so a token or key in it cannot slip
/// into history while the background checker is on it. Pure.
pub fn copy_verdict(found: &Found) -> PictureVerdict {
    PictureVerdict {
        concealed: !found.labels.is_empty(),
        admitted: !found.labels.contains(&Label::Credential),
    }
}

/// What an Image ▾ step's own recognition changes about its copy, made with `before`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct Recheck {
    /// Mark the clipboard's copy Concealed now (if the clipboard still holds it).
    pub conceal: bool,
    /// Take the copy out of history again (it shows a token, key or URL password; a turned
    /// picture can be read where the original could not).
    pub retract: bool,
}

/// [`Recheck`] for a step's copy made with `before`, now that its own text is `recognised`.
/// Only ever stricter: a copy concealed or kept out on the original's text stays so. Pure.
pub fn picture_recheck(before: PictureVerdict, recognised: Option<&str>) -> Recheck {
    let now = picture_verdict(recognised);
    Recheck {
        conceal: now.concealed && !before.concealed,
        retract: before.admitted && !now.admitted,
    }
}

/// The labels for the card: a short copy is checked now, a longer one is remembered or handed
/// to the background checker ([`Labeling::Checking`]).
pub fn labeling(text: &str) -> Labeling {
    if text.len() < SYNC_LIMIT {
        return Labeling::Known(found(text));
    }
    if let Some(known) = LABELS.get(text) {
        return Labeling::Known(known);
    }
    checker::request(text);
    Labeling::Checking
}

/// Is `text` known to hold nothing sensitive (no label at all)? A long copy whose labels are
/// still being checked is not: the hash of a sensitive card stays out of history
/// (`App::finish_text`).
pub fn is_plain(text: &str) -> bool {
    matches!(labeling(text), Labeling::Known(found) if found.labels.is_empty())
}

/// Run `hook` (from the checker thread) whenever the checker has labels for a copy.
pub fn on_checked(hook: fn()) {
    checker::on_ready(hook);
}

/// The meta-line status at the end of `meta`, if any: [`checking`].
pub fn meta_status(meta: &str) -> Option<&'static str> {
    meta.ends_with(&format!("  ·  {}", checking()))
        .then(checking)
}

pub fn label_line(labels: &[Label]) -> String {
    labels
        .iter()
        .map(|label| label.name())
        .collect::<Vec<_>>()
        .join(" · ")
}

/// One sensitivity name inside a meta line. Indexes are byte offsets.
pub struct WarningMark {
    pub start: usize,
    pub end: usize,
    pub label: Label,
}

/// Labels at the end of a meta line, such as `0.249 KB  ·  PII · financial`.
/// The size and filename stay outside these ranges.
pub fn warning_marks(meta: &str) -> Vec<WarningMark> {
    let meta = match meta_status(meta) {
        Some(status) => &meta[..meta.len() - status.len() - "  ·  ".len()],
        None => meta,
    };
    let Some(suffix_at) = meta.rfind("  ·  ") else {
        return Vec::new();
    };
    let suffix_at = suffix_at + "  ·  ".len();
    let suffix = &meta[suffix_at..];
    if suffix.is_empty() {
        return Vec::new();
    }
    let mut marks = Vec::new();
    let mut offset = suffix_at;
    for part in suffix.split(" · ") {
        let start = offset;
        let end = start + part.len();
        let Some(label) = label_named(part) else {
            return Vec::new();
        };
        marks.push(WarningMark { start, end, label });
        offset = end + " · ".len();
    }
    marks
}

fn label_named(name: &str) -> Option<Label> {
    // A meta line is built in the launch language; both names are accepted all the same.
    use crate::locale::{Lang, t_in};
    let key = |label: Label| match label {
        Label::Credential => "label_credential",
        Label::Pii => "label_pii",
        Label::Financial => "label_financial",
    };
    Label::ALL.into_iter().find(|label| {
        [Lang::En, Lang::Nl]
            .iter()
            .any(|lang| t_in(*lang, key(*label)) == name)
    })
}

/// Kinds present in `text`, one label each, in [`Label`] order.
/// Named columns such as Naam or Salaris count too.
/// Rust and Java are source: a path or a field name is not personal data,
/// so those cards do not pick up a PII label. A real key or account still does.
/// Remembered for large texts (see [`crate::memo`]): scanning a large copy takes hundreds of
/// milliseconds and the card asks on every redraw.
#[cfg(test)]
pub fn labels(text: &str) -> Vec<Label> {
    found(text).labels
}

/// The labels of `text`, computed here and now and not remembered (one line of a file).
pub fn scan_labels(text: &str) -> Vec<Label> {
    scan(text, &|| false).unwrap_or_default().labels
}

/// The labels of `text`, computed here and now (or remembered).
pub fn found(text: &str) -> Found {
    LABELS.get_or_compute(text, |text| scan(text, &|| false).unwrap_or_default())
}

static LABELS: crate::memo::Memo<Found> = crate::memo::Memo::new(8);

/// Drop the remembered labels and any check in progress (Wipe).
pub fn forget_labels() {
    checker::forget();
    LABELS.clear();
}

/// Scan `text`. `None` when `cancelled` said so between two stages (a newer copy came in).
///
/// First copycraft's own recognizers ([`crate::recognize`]), then leakguard, only for the
/// classes they did not find. Both are linear: about 60 ms for a megabyte (release build).
fn scan(text: &str, cancelled: &dyn Fn() -> bool) -> Option<Found> {
    let kind = crate::format::detect(text);
    // Source code, a crash report and a log hold no personal or financial data: a path, a
    // process id, `User ID: 501`, a timestamp or an address is no person and no card. A real
    // key or token in them still counts.
    let code = is_code(kind)
        || (matches!(kind, FormatKind::Text | FormatKind::Plain)
            && crate::log_text::detect(text).is_some());
    let scope = if code {
        crate::recognize::Scope::Code
    } else if is_docs(kind) {
        crate::recognize::Scope::Docs
    } else {
        crate::recognize::Scope::Plain
    };
    if cancelled() {
        return None;
    }
    let mut classes = crate::recognize::classes(text, scope);
    if !classes.all() {
        if cancelled() {
            return None;
        }
        // Code and logs: only the credential detectors.
        let wanted = if code {
            crate::recognize::Classes {
                pii: true,
                financial: true,
                ..classes
            }
        } else {
            classes
        };
        for hit in guard_for(wanted).find(text) {
            let label = label_for(&hit.kind);
            // Documentation: the recognizers already decided on e-mail addresses (a few are a
            // support line, not a person).
            if scope == crate::recognize::Scope::Docs && hit.kind == Kind::Email {
                continue;
            }
            if counts(text, &hit) && !(code && label != Label::Credential) {
                classes = with(classes, label);
            }
        }
    }
    Some(Found {
        labels: classes.labels(),
    })
}

fn with(mut classes: crate::recognize::Classes, label: Label) -> crate::recognize::Classes {
    match label {
        Label::Credential => classes.credential = true,
        Label::Pii => classes.pii = true,
        Label::Financial => classes.financial = true,
    }
    classes
}

/// Build the recognizers and the full leakguard set now (on a background thread at launch),
/// so the first card does not wait for them.
pub fn warm() {
    crate::recognize::warm();
    guard_for(crate::recognize::Classes::default());
}

/// Leakguard with only the detectors of the classes not found yet, built once per combination.
fn guard_for(found: crate::recognize::Classes) -> &'static Redactor {
    static GUARDS: [OnceLock<Redactor>; 8] = [const { OnceLock::new() }; 8];
    let missing = usize::from(!found.credential)
        | usize::from(!found.pii) << 1
        | usize::from(!found.financial) << 2;
    GUARDS[missing].get_or_init(|| {
        let mut kinds = Vec::new();
        if !found.credential {
            kinds.extend([
                Kind::PrivateKey,
                Kind::AzureConnectionString,
                Kind::TelegramToken,
                Kind::DiscordToken,
                Kind::Jwt,
                Kind::GitHubToken,
                Kind::SlackToken,
                Kind::StripeKey,
                Kind::OpenAiKey,
                Kind::GoogleApiKey,
                Kind::AwsAccessKey,
                Kind::UrlCredentials,
            ]);
        }
        if !found.pii {
            kinds.extend([
                Kind::Email,
                Kind::IpV6,
                Kind::IpV4,
                Kind::MacAddress,
                Kind::UsSsn,
            ]);
        }
        if !found.financial {
            kinds.extend([Kind::Iban, Kind::CreditCard]);
        }
        Redactor::only(&kinds)
    })
}

/// The background checker: one thread, one job at a time. A new request supersedes the waiting
/// job and cancels the running one at its next stage (generation counter); a result whose
/// generation is no longer current is dropped. Its copy of the text is zeroized with the job.
mod checker {
    use std::sync::atomic::{AtomicU64, Ordering};
    use std::sync::{Condvar, Mutex, MutexGuard, OnceLock};

    use super::Zeroizing;

    struct Job {
        generation: u64,
        text: Zeroizing<String>,
    }

    struct State {
        job: Option<Job>,
        /// Key of the text waiting or being checked, so the card asking again adds nothing.
        asked: Option<(usize, u64)>,
    }

    static STATE: Mutex<State> = Mutex::new(State {
        job: None,
        asked: None,
    });
    static WAKE: Condvar = Condvar::new();
    static GENERATION: AtomicU64 = AtomicU64::new(0);
    static READY: OnceLock<fn()> = OnceLock::new();
    static STARTED: OnceLock<()> = OnceLock::new();

    fn state() -> MutexGuard<'static, State> {
        STATE.lock().unwrap_or_else(|err| err.into_inner())
    }

    pub fn on_ready(hook: fn()) {
        let _ = READY.set(hook);
    }

    pub fn request(text: &str) {
        let key = crate::memo::text_key(text);
        let mut state = state();
        if state.asked == Some(key) {
            return;
        }
        let generation = GENERATION.fetch_add(1, Ordering::SeqCst) + 1;
        state.job = Some(Job {
            generation,
            text: Zeroizing::new(text.to_string()),
        });
        state.asked = Some(key);
        drop(state);
        start();
        WAKE.notify_one();
    }

    pub fn forget() {
        GENERATION.fetch_add(1, Ordering::SeqCst);
        let mut state = state();
        state.job = None;
        state.asked = None;
    }

    fn start() {
        STARTED.get_or_init(|| {
            if let Err(e) = std::thread::Builder::new()
                .name("copycraft-checker".into())
                .spawn(run)
            {
                crate::diag::log(crate::diag::LogEvent::SensitivityNotStarted(
                    crate::diag::ErrorKind::io(&e),
                ));
            }
        });
    }

    fn run() {
        loop {
            let job = {
                let mut state = state();
                loop {
                    if let Some(job) = state.job.take() {
                        break job;
                    }
                    state = WAKE.wait(state).unwrap_or_else(|err| err.into_inner());
                }
            };
            let current = || GENERATION.load(Ordering::SeqCst) == job.generation;
            let started = std::time::Instant::now();
            let found = super::scan(&job.text, &|| !current());
            if !current() {
                continue;
            }
            state().asked = None;
            let Some(found) = found else {
                continue;
            };
            crate::diag::log(crate::diag::LogEvent::SensitivityChecked {
                kb: (job.text.len() / 1024) as u64,
                ms: started.elapsed().as_millis() as u64,
            });
            super::LABELS.put(&job.text, found);
            if let Some(hook) = READY.get() {
                hook();
            }
        }
    }
}

fn is_docs(kind: FormatKind) -> bool {
    matches!(kind, FormatKind::Markdown | FormatKind::Agent)
}

fn is_code(kind: FormatKind) -> bool {
    matches!(
        kind,
        FormatKind::Rust | FormatKind::Java | FormatKind::Python
    )
}

/// `std::io` is hex letters around `::`, which is the shape of a compressed
/// IPv6 address. An address has a digit (`fe80::1`). A rust path does not.
/// A card number or IBAN counts only standalone: a digit run inside a hex hash or another
/// token (`checksum = "c982642fa9…"`) is no card.
fn counts(text: &str, hit: &Match) -> bool {
    match hit.kind {
        // Standalone, so `u64::MAX` in code or prose is no address `64::`.
        Kind::IpV6 => {
            standalone(text.as_bytes(), hit.start, hit.end)
                && text[hit.start..hit.end]
                    .bytes()
                    .any(|byte| byte.is_ascii_digit())
        }
        // The same rules as copycraft's own recognizers: a card needs a known issuer prefix,
        // Luhn and to stand on its own (not a hex value, an ID in a URL path, a decimal); an
        // IBAN its mod-97.
        Kind::CreditCard => crate::recognize::card_number(text.as_bytes(), hit.start, hit.end),
        Kind::Iban => crate::recognize::iban(text.as_bytes(), hit.start, hit.end),
        _ => true,
    }
}

fn standalone(bytes: &[u8], start: usize, end: usize) -> bool {
    let token = |at: Option<&u8>| at.is_some_and(|b| b.is_ascii_alphanumeric() || *b == b'_');
    !token(start.checked_sub(1).and_then(|at| bytes.get(at))) && !token(bytes.get(end))
}

fn label_for(kind: &Kind) -> Label {
    match kind {
        Kind::CreditCard | Kind::Iban => Label::Financial,
        Kind::Email
        | Kind::UsSsn
        | Kind::PhoneNumber
        | Kind::IpV4
        | Kind::IpV6
        | Kind::MacAddress => Label::Pii,
        Kind::Jwt
        | Kind::AwsAccessKey
        | Kind::UrlCredentials
        | Kind::GitHubToken
        | Kind::SlackToken
        | Kind::StripeKey
        | Kind::GoogleApiKey
        | Kind::OpenAiKey
        | Kind::PrivateKey
        | Kind::AzureConnectionString
        | Kind::TelegramToken
        | Kind::DiscordToken
        | Kind::GenericSecret
        | Kind::Custom(_) => Label::Credential,
        _ => Label::Credential,
    }
}

