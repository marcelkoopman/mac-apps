    use super::{Label, label_line, labels, warning_marks};

    /// The history gate ([`super::admission`]): a copy recognised as a token, key or URL
    /// password is refused, PII and financial data are kept (masked), a long copy waits.
    #[test]
    fn tokens_and_keys_stay_out_of_history() {
        use super::{Admission, Found, Labeling, admission, labeling};
        // A GitHub token: `ghp_` and 36 characters (split, so secret scanners skip the test).
        let token = concat!("gh", "p_", "aBcDeFgHiJkLmNoPqRsTuVwXyZ0123456789");
        assert_eq!(token.len(), 4 + 36);
        assert_eq!(admission(&labeling(token)), Admission::Refuse);
        let line = format!("export GITHUB_TOKEN={token}\n");
        assert_eq!(admission(&labeling(&line)), Admission::Refuse);
        for secret in [
            concat!("AK", "IAIOSFODNN7EXAMPLE"),
            concat!("xo", "xb-123456789012-abcdefghijkl"),
            concat!("sk_", "live_51H8abcdefghijklmnop"),
            concat!(
                "-----BEGIN OPENSSH PRIVATE ",
                "KEY-----\nb3BlbnNzaC1rZXktdjEAAAAA\n-----END OPENSSH PRIVATE ",
                "KEY-----"
            ),
        ] {
            assert_eq!(admission(&labeling(secret)), Admission::Refuse, "{secret}");
        }
        for kept in [
            "hello world",
            "mail me at jan.devries@email.nl please",
            "pay to NL91ABNA0417164300",
        ] {
            assert_eq!(admission(&labeling(kept)), Admission::Keep, "{kept}");
        }
        assert_eq!(admission(&Labeling::Checking), Admission::Wait);
        let mixed = Found {
            labels: vec![Label::Credential, Label::Pii],
        };
        assert_eq!(admission(&Labeling::Known(mixed)), Admission::Refuse);
        assert_eq!(
            admission(&Labeling::Known(Found::default())),
            Admission::Keep
        );
    }

