    let mut history = ClipboardHistory::default();
    let mut ids = Vec::new();
    for i in 0..super::PIN_MAX {
        history.record(format!("pin {i}"));
        let id = history.id_at(0).expect("id");
        assert!(history.pin(id));
        ids.push(id);
    }
    history.record("extra".into());
